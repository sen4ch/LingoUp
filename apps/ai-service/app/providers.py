"""Backend adapters. Each task returns validated output or raises ProviderError."""

import json
import re
from typing import Any, Literal, Protocol

import httpx
from pydantic import BaseModel, ValidationError

from .config import Settings
from .prompts import (
    EXERCISE_SCHEMA,
    OUTPUT_SCHEMA,
    READING_TEXT_SCHEMA,
    Messages,
    exercise_messages,
    reading_text_messages,
    word_explanation_messages,
)
from .schemas import (
    GAP,
    ExerciseGenerationInput,
    ExerciseGenerationOutput,
    ExerciseItem,
    ReadingTextGenerationInput,
    ReadingTextGenerationOutput,
    WordExplanationInput,
    WordExplanationOutput,
)


class ProviderError(Exception):
    """Upstream failure or unusable model output. Mapped to HTTP 502 (retryable)."""


class Provider(Protocol):
    name: str
    model: str
    data_locality: Literal["local", "external"]

    async def explain_word(self, task: WordExplanationInput) -> WordExplanationOutput: ...

    async def generate_text(
        self, task: ReadingTextGenerationInput
    ) -> ReadingTextGenerationOutput: ...

    async def generate_exercises(
        self, task: ExerciseGenerationInput
    ) -> ExerciseGenerationOutput: ...

    async def warm_up(self) -> None: ...

    async def aclose(self) -> None: ...


def parse_output[Output: BaseModel](raw: str, model: type[Output]) -> Output:
    try:
        return model.model_validate(json.loads(raw))
    except (json.JSONDecodeError, ValidationError) as error:
        raise ProviderError("Model returned output that does not match the schema") from error


def blank_term(sentence: str, term: str) -> str | None:
    """Returns the sentence with a gap, blanking the term when the model left it in."""
    if GAP in sentence:
        return sentence if sentence.count(GAP) == 1 else None
    pattern = re.compile(rf"(?<![\w-]){re.escape(term)}(?![\w-])", re.IGNORECASE)
    if len(pattern.findall(sentence)) != 1:
        return None
    return pattern.sub(GAP, sentence)


def parse_exercises(raw: str) -> ExerciseGenerationOutput:
    """Keeps the usable items: small models often forget to blank the word or skip a field."""
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as error:
        raise ProviderError("Model returned output that does not match the schema") from error
    candidates = data.get("items") if isinstance(data, dict) else None
    items: list[ExerciseItem] = []
    for candidate in candidates if isinstance(candidates, list) else []:
        if not isinstance(candidate, dict):
            continue
        term, sentence = candidate.get("term"), candidate.get("sentence")
        if not isinstance(term, str) or not isinstance(sentence, str):
            continue
        gapped = blank_term(sentence, term)
        if gapped is None:
            continue
        try:
            items.append(ExerciseItem.model_validate({**candidate, "sentence": gapped}))
        except ValidationError:
            continue
    try:
        return ExerciseGenerationOutput(items=items[:10])
    except ValidationError as error:
        raise ProviderError("Model returned no usable exercises") from error


class MockProvider:
    """Deterministic placeholder; output is explicitly labelled as such."""

    name = "mock"
    model = "mock-v1"
    data_locality: Literal["local", "external"] = "local"

    async def explain_word(self, task: WordExplanationInput) -> WordExplanationOutput:
        return WordExplanationOutput(
            definition=(
                f'Placeholder for "{task.term}": the ai-service runs with AI_BACKEND=mock. '
                "Configure Ollama or an OpenAI-compatible backend for real explanations."
            ),
            example=task.context.strip() or None,
        )

    async def generate_text(self, task: ReadingTextGenerationInput) -> ReadingTextGenerationOutput:
        return ReadingTextGenerationOutput(
            title="Placeholder practice text",
            summary="Generated by AI_BACKEND=mock. Configure a real backend for real texts.",
            paragraphs=[
                "This is a placeholder text from the mock backend.",
                *[
                    " ".join(
                        f'Here is the word "{word}" in a placeholder sentence.'
                        for word in task.words[start : start + 10]
                    )
                    for start in range(0, len(task.words), 10)
                ],
            ],
        )

    async def generate_exercises(self, task: ExerciseGenerationInput) -> ExerciseGenerationOutput:
        return ExerciseGenerationOutput(
            items=[
                ExerciseItem(
                    term=word.term,
                    sentence=f"Placeholder sentence from the mock backend: {GAP}.",
                    hint=word.definition,
                )
                for word in task.words
            ]
        )

    async def warm_up(self) -> None:
        return None

    async def aclose(self) -> None:
        return None


class LlmProvider:
    """Tasks on top of a backend that turns chat messages into JSON matching a schema."""

    name: str
    model: str
    data_locality: Literal["local", "external"]

    async def complete_json(
        self, messages: Messages, schema: dict[str, Any], temperature: float
    ) -> str:
        raise NotImplementedError

    async def explain_word(self, task: WordExplanationInput) -> WordExplanationOutput:
        raw = await self.complete_json(word_explanation_messages(task), OUTPUT_SCHEMA, 0.2)
        return parse_output(raw, WordExplanationOutput)

    async def generate_text(self, task: ReadingTextGenerationInput) -> ReadingTextGenerationOutput:
        raw = await self.complete_json(reading_text_messages(task), READING_TEXT_SCHEMA, 0.7)
        return parse_output(raw, ReadingTextGenerationOutput)

    async def generate_exercises(self, task: ExerciseGenerationInput) -> ExerciseGenerationOutput:
        raw = await self.complete_json(exercise_messages(task), EXERCISE_SCHEMA, 0.5)
        return parse_exercises(raw)

    async def warm_up(self) -> None:
        return None


class OllamaProvider(LlmProvider):
    """Local models via Ollama's /api/chat with JSON-schema constrained output."""

    name = "ollama"
    data_locality: Literal["local", "external"] = "local"

    def __init__(self, settings: Settings) -> None:
        self.model = settings.ollama_model
        self._think = settings.ollama_think
        self._keep_alive = settings.ollama_keep_alive
        self._client = httpx.AsyncClient(
            base_url=settings.ollama_url, timeout=settings.request_timeout_seconds
        )

    async def warm_up(self) -> None:
        """Loads the model into memory; a request without a prompt only loads it."""
        response = await self._client.post(
            "/api/generate", json={"model": self.model, "keep_alive": self._keep_alive}
        )
        response.raise_for_status()

    async def complete_json(
        self, messages: Messages, schema: dict[str, Any], temperature: float
    ) -> str:
        try:
            response = await self._client.post(
                "/api/chat",
                json={
                    "model": self.model,
                    "messages": messages,
                    "format": schema,
                    "stream": False,
                    "keep_alive": self._keep_alive,
                    "options": {"temperature": temperature},
                    **({} if self._think is None else {"think": self._think}),
                },
            )
            response.raise_for_status()
            return str(response.json()["message"]["content"])
        except (httpx.HTTPError, KeyError, ValueError) as error:
            raise ProviderError(f"Ollama request failed: {type(error).__name__}") from error

    async def aclose(self) -> None:
        await self._client.aclose()


class OpenAICompatibleProvider(LlmProvider):
    """vLLM, LocalAI or any OpenAI-compatible /v1/chat/completions endpoint."""

    name = "openai-compatible"

    def __init__(self, settings: Settings) -> None:
        if not settings.openai_compatible_base_url or not settings.openai_compatible_model:
            raise ValueError(
                "OPENAI_COMPATIBLE_BASE_URL and OPENAI_COMPATIBLE_MODEL are required "
                "for AI_BACKEND=openai-compatible"
            )
        self.model = settings.openai_compatible_model
        self.data_locality = settings.openai_compatible_data_locality
        api_key = settings.openai_compatible_api_key.get_secret_value()
        self._client = httpx.AsyncClient(
            base_url=settings.openai_compatible_base_url.rstrip("/"),
            timeout=settings.request_timeout_seconds,
            headers={"authorization": f"Bearer {api_key}"} if api_key else {},
        )

    async def complete_json(
        self, messages: Messages, schema: dict[str, Any], temperature: float
    ) -> str:
        # json_object mode is widely supported; the schema is enforced by validation instead.
        del schema
        try:
            response = await self._client.post(
                "/chat/completions",
                json={
                    "model": self.model,
                    "messages": messages,
                    "response_format": {"type": "json_object"},
                    "temperature": temperature,
                },
            )
            response.raise_for_status()
            return str(response.json()["choices"][0]["message"]["content"])
        except (httpx.HTTPError, KeyError, IndexError, ValueError) as error:
            raise ProviderError(
                f"OpenAI-compatible request failed: {type(error).__name__}"
            ) from error

    async def aclose(self) -> None:
        await self._client.aclose()


def create_provider(settings: Settings) -> Provider:
    match settings.ai_backend:
        case "mock":
            return MockProvider()
        case "ollama":
            return OllamaProvider(settings)
        case "openai-compatible":
            return OpenAICompatibleProvider(settings)
